#include "core/Evaluator.h"
#include <QDateTime>

Result StandardEvaluator::evaluate(const ExamSession& session) {
    const Quiz& quiz = session.getQuiz();
    int totalQuestions = quiz.getQuestionCount();

    int correctAnswers = 0;
    int incorrectAnswers = 0;
    int unansweredQuestions = 0;

    int totalMarks = 0;
    int marksObtained = 0;

    for (int i = 0; i < totalQuestions; ++i) {
        const Question* q = quiz.getQuestionAt(i);
        if (!q) continue;

        int questionMarks = q->getMarks();
        totalMarks += questionMarks;

        int selectedAnswer = session.getSelectedAnswer(i);

        if (selectedAnswer == -1) {
            unansweredQuestions++;
        } else if (q->isCorrect(selectedAnswer)) {
            correctAnswers++;
            marksObtained += questionMarks;
        } else {
            incorrectAnswers++;
        }
    }

    // Guard against divide by zero if totalMarks is 0
    double percentage = 0.0;
    if (totalMarks > 0) {
        percentage = (static_cast<double>(marksObtained) / totalMarks) * 100.0;
    }

    bool isPassed = (percentage >= quiz.getPassPercentage());

    return Result(
        0, // ID generated by DB
        session.getStudentId(),
        quiz.getId(),
        totalQuestions,
        correctAnswers,
        incorrectAnswers,
        unansweredQuestions,
        totalMarks,
        marksObtained,
        percentage,
        isPassed,
        QDateTime::currentDateTime(),
        session.getElapsedTimeSeconds(),
        "", "", "",
        session.getProctorWarnings(),
        session.getIntegrityScore()
    );
}
